import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {projectRoot,sourceLock} from './inputs.mjs';
import {files} from './files.mjs';
import {SHELL_VERSION} from '../../web/src/core/online-catalog.mjs';
for(const directory of ['scripts/web','web/src','tests/web','e2e/web'])for(const file of files(join(projectRoot,directory)).filter(f=>/\.(?:mjs|js)$/.test(f.path)))execFileSync(process.execPath,['--check',join(projectRoot,directory,file.path)],{stdio:'inherit'});
const lock=sourceLock();const packageInfo=JSON.parse(readFileSync(join(projectRoot,'web/package.json')));
if(packageInfo.type!=='module'||packageInfo.version!==SHELL_VERSION)throw Error('Independent web version contract');
console.log(`Web syntax and immutable source contract valid (${lock.sources.length} games)`);
